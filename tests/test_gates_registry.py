"""internal_docs/program/gates.md must list every check_quirks.py rule (scripts/gates_registry.py)."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("gates_registry", ROOT / "scripts" / "gates_registry.py")
gates_registry = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = gates_registry
_spec.loader.exec_module(gates_registry)


def test_gates_md_is_current(capsys):
    code = gates_registry.main(["--check"])
    assert code == 0, capsys.readouterr().out


def test_every_rule_has_a_row():
    text = (ROOT / gates_registry.GATES).read_text(encoding="utf-8")
    for rule in gates_registry._load_quirks().RULES:
        assert f"| quirk `{rule}` |" in text


def test_hand_deleted_quirk_row_fails_check(tmp_path, monkeypatch, capsys):
    text = (ROOT / gates_registry.GATES).read_text(encoding="utf-8")
    kept = [ln for ln in text.splitlines() if not ln.startswith("| quirk `vtk-import`")]
    assert len(kept) == len(text.splitlines()) - 1
    fake = tmp_path / "gates.md"
    fake.write_text("\n".join(kept) + "\n", encoding="utf-8")
    monkeypatch.setattr(gates_registry, "GATES", fake)
    assert gates_registry.main(["--check"]) == 1
    assert "missing row: quirk `vtk-import`" in capsys.readouterr().out


def test_edited_waiver_count_fails_check(tmp_path, monkeypatch):
    text = (ROOT / gates_registry.GATES).read_text(encoding="utf-8")
    lines = text.splitlines()
    i = next(n for n, ln in enumerate(lines) if ln.startswith("| quirk `adr-number`"))
    cells = lines[i].split(" | ")
    cells[-2] = "9"
    lines[i] = " | ".join(cells)
    fake = tmp_path / "gates.md"
    fake.write_text("\n".join(lines) + "\n", encoding="utf-8")
    monkeypatch.setattr(gates_registry, "GATES", fake)
    assert gates_registry.main(["--check"]) == 1


def _check_text(tmp_path, monkeypatch, lines):
    fake = tmp_path / "gates.md"
    fake.write_text("\n".join(lines) + "\n", encoding="utf-8")
    monkeypatch.setattr(gates_registry, "GATES", fake)
    return gates_registry.main(["--check"])


def _lines():
    return (ROOT / gates_registry.GATES).read_text(encoding="utf-8").splitlines()


def test_every_quirks_ratchet_file_has_a_row():
    text = (ROOT / gates_registry.GATES).read_text(encoding="utf-8")
    files = sorted((ROOT / "scripts").glob("quirks_*.txt"))
    assert files
    for path in files:
        assert f"| ratchet `scripts/{path.name}`" in text


def test_duplicated_quirk_row_fails_check(tmp_path, monkeypatch, capsys):
    lines = _lines()
    i = next(n for n, ln in enumerate(lines) if ln.startswith("| quirk `adr-number`"))
    lines.insert(i, lines[i])
    assert _check_text(tmp_path, monkeypatch, lines) == 1
    assert "duplicate row" in capsys.readouterr().out


def test_reordered_quirk_rows_fail_check(tmp_path, monkeypatch, capsys):
    lines = _lines()
    i = next(n for n, ln in enumerate(lines) if ln.startswith("| quirk `adr-number`"))
    lines[i], lines[i + 1] = lines[i + 1], lines[i]
    assert _check_text(tmp_path, monkeypatch, lines) == 1
    assert "out of order" in capsys.readouterr().out


def test_stale_preamble_fails_check(tmp_path, monkeypatch):
    lines = _lines()
    i = next(n for n, ln in enumerate(lines) if ln.startswith("Generated by"))
    lines[i] = "Derived by the commands in the PR that created this file (#1481); regenerate, never hand-edit."
    assert _check_text(tmp_path, monkeypatch, lines) == 1


def test_reworded_header_fails_check(tmp_path, monkeypatch, capsys):
    lines = _lines()
    i = next(n for n, ln in enumerate(lines) if ln.startswith("| Gate "))
    lines[i] = lines[i].replace("Purpose", "What it is for")
    assert _check_text(tmp_path, monkeypatch, lines) == 1
    assert "header" in capsys.readouterr().out


def test_duplicated_lock_row_fails_check(tmp_path, monkeypatch, capsys):
    lines = _lines()
    i = next(n for n, ln in enumerate(lines) if ln.startswith("| lock `"))
    lines.insert(i, lines[i])
    assert _check_text(tmp_path, monkeypatch, lines) == 1
    assert "duplicate row" in capsys.readouterr().out


def test_ratchet_row_for_deleted_file_fails_check(tmp_path, monkeypatch, capsys):
    lines = _lines()
    i = next(n for n, ln in enumerate(lines) if ln.startswith("| ratchet `scripts/quirks_"))
    stale = lines[i].replace("quirks_getattr_baseline.txt", "quirks_deleted_long_ago.txt")
    stale = stale.replace("quirks_render_allowlist.txt", "quirks_deleted_long_ago.txt")
    assert "quirks_deleted_long_ago" in stale
    lines.insert(i, stale)
    assert _check_text(tmp_path, monkeypatch, lines) == 1
    assert "stale row: ratchet `scripts/quirks_deleted_long_ago.txt`" in capsys.readouterr().out
