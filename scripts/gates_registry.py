"""Regenerate the quirk rows of internal_docs/program/gates.md from scripts/check_quirks.py.

    python scripts/gates_registry.py           # rewrite the file
    python scripts/gates_registry.py --check   # exit 1 on drift, touching nothing

A quirk row carries the rule name, its purpose (the opening clause of its RULES text),
the legitimate way to change it, and the waiver count (the `# apegmsh-lint: <rule>-ok`
comments in the scanned tree). Lock, ratchet and label rows are kept as written.
Owner and Review are read from the existing file for a rule that already has a row;
a new row takes the chain tag of the commit that introduced the rule (`git log -S`),
or `?`. `--check` compares every column except Owner, so it needs no git history.
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GATES = Path("internal_docs/program/gates.md")
PURPOSE_CAP = 150
OWNER = 1
HEADER = "| Gate | Owner | Purpose | Legitimate way to change | Waivers | Review |"
RATCHET_FILE = re.compile(r"ratchet `scripts/(quirks_[^`]+\.txt)`")


def _load_quirks():
    spec = importlib.util.spec_from_file_location("check_quirks", ROOT / "scripts" / "check_quirks.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def purpose(text: str) -> str:
    """The opening clause of a rule's text: up to the first ': ' or '. ', capped."""
    cut = min((i for i in (text.find(": "), text.find(". ")) if i > 0), default=len(text))
    clause = text[:cut].strip()
    if len(clause) > PURPOSE_CAP:
        clause = clause[: PURPOSE_CAP - 1].rstrip() + "…"
    return clause.replace("|", "/")


def waiver_counts(quirks, root: Path) -> dict[str, int]:
    """`# apegmsh-lint: <rule>-ok` comments per rule, over the files check_quirks scans."""
    counts = {rule: 0 for rule in quirks.RULES}
    for path in quirks._python_files(root):
        if path.name in ("check_quirks.py", "test_check_quirks.py"):
            continue  # they quote the waiver syntax in fixtures and docs
        text = quirks._read_source(path)
        if text is None or "apegmsh-lint" not in text.lower():
            continue
        for comment in quirks._comments(text).values():
            match = quirks.WAIVER.search(comment)
            if match and match.group("rule") in counts:
                counts[match.group("rule")] += 1
    return counts


def introduced_by(rule: str, root: Path) -> str:
    """The chain tag in the subject of the commit that added the rule, else '?'."""
    try:
        out = subprocess.run(
            ["git", "log", "--reverse", "--format=%s", "-S", f'"{rule}"', "--", "scripts/check_quirks.py"],
            cwd=root, capture_output=True, text=True, timeout=60, check=False,
        ).stdout.splitlines()
    except (OSError, subprocess.SubprocessError):
        return "?"
    match = re.match(r"\[([A-Z]\w*?)(?:-\w+)?\]", out[0]) if out else None
    return match.group(1) if match else "?"


PREAMBLE = (
    "Generated by `python scripts/gates_registry.py` from `scripts/check_quirks.py` (quirk rows, "
    "waiver counts) and the `scripts/quirks_*.txt` ratchet files; regenerate, never hand-edit. "
    "`python scripts/gates_registry.py --check` fails CI on drift. Owner is the chain tag of the "
    "commit that introduced the gate, `?` where the history names none. Next review: {review}."
)
#: Shrink-only lists beside check_quirks.py, one ratchet row each.
RATCHET_LABELS = {
    "quirks_getattr_baseline.txt": "getattr-undefined ratchet",
    "quirks_render_allowlist.txt": "vtk-import / render-tech-import ratchet",
}
RATCHET_PURPOSE = "a count or set that may only shrink"
RATCHET_CHANGE = "lower it freely; raising it is a maintainer gate (PROGRAM.md section 4)"


def ratchet_gate(path: Path) -> str:
    label = RATCHET_LABELS.get(path.name, "ratchet")
    return f"ratchet `scripts/{path.name}` ({label})"


def _first_commit_tag(root: Path, rel: str) -> str:
    try:
        out = subprocess.run(
            ["git", "log", "--reverse", "--diff-filter=A", "--format=%s", "--", rel],
            cwd=root, capture_output=True, text=True, timeout=60, check=False,
        ).stdout.splitlines()
    except (OSError, subprocess.SubprocessError):
        return "?"
    match = re.match(r"\[([A-Z]\w*?)(?:-\w+)?\]", out[0]) if out else None
    return match.group(1) if match else "?"


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split(" | ")]


def quirk_row(quirks, rule: str, waivers: int, owner: str, review: str) -> list[str]:
    if rule in quirks.NO_WAIVER:
        change = "change the rule in `scripts/check_quirks.py` with its self-test; it has no per-site waiver"
    else:
        change = (
            f"fix the code, or waive one site with `# apegmsh-lint: {rule}-ok <reason>`; "
            "change the rule in `scripts/check_quirks.py` with its self-test"
        )
    return [f"quirk `{rule}`", owner, purpose(quirks.RULES[rule]), change, str(waivers), review]


def build(root: Path, existing: str, use_git: bool) -> str:
    quirks = _load_quirks()
    lines = existing.splitlines()
    header = next((i for i, ln in enumerate(lines) if ln.startswith("| Gate ")), None)
    if header is None:
        raise ValueError("gates.md has no table header line starting with '| Gate '; restore it")
    sep = header + 1
    table_end = next((i for i in range(sep + 1, len(lines)) if not lines[i].startswith("|")), len(lines))
    body = []
    seen: set[str] = set()
    for ln in lines[sep + 1 : table_end]:  # a duplicated row keeps its first occurrence
        if _cells(ln)[0] not in seen:
            seen.add(_cells(ln)[0])
            body.append(ln)
    old = {_cells(ln)[0]: _cells(ln) for ln in body}
    nxt = re.search(r"Next review:\s*(\d{4}-\d{2}-\d{2})", existing)
    default_review = nxt.group(1) if nxt else "?"
    counts = waiver_counts(quirks, root)

    rows = []
    for rule in quirks.RULES:
        prior = old.get(f"quirk `{rule}`")
        owner = prior[OWNER] if prior else (introduced_by(rule, root) if use_git else "?")
        review = prior[5] if prior else default_review
        rows.append("| " + " | ".join(quirk_row(quirks, rule, counts[rule], owner, review)) + " |")

    # a ratchet row whose quirks_*.txt file is gone is stale: drop it
    body = [
        ln for ln in body
        if not (m := RATCHET_FILE.match(_cells(ln)[0])) or (root / "scripts" / m.group(1)).exists()
    ]
    present = [_cells(ln)[0] for ln in body]
    missing = []
    for path in sorted((root / "scripts").glob("quirks_*.txt")):
        if not any(g.startswith(f"ratchet `scripts/{path.name}`") for g in present):
            owner = _first_commit_tag(root, f"scripts/{path.name}") if use_git else "?"
            missing.append(
                f"| {ratchet_gate(path)} | {owner} | {RATCHET_PURPOSE} | {RATCHET_CHANGE} | 0 | {default_review} |"
            )
    last_ratchet = max((i for i, ln in enumerate(body) if _cells(ln)[0].startswith("ratchet `")), default=-1)
    body = body[: last_ratchet + 1] + missing + body[last_ratchet + 1 :]

    out: list[str] = []
    placed = False
    for ln in body:
        if _cells(ln)[0].startswith("quirk `"):
            if not placed:
                out += rows
                placed = True
        else:
            out.append(ln)
    if not placed:
        out = rows + out
    head = lines[: sep + 1]
    head[header] = HEADER
    for i, ln in enumerate(head):
        if ln.startswith(("Derived by", "Generated by")):
            head[i] = PREAMBLE.format(review=default_review)
    return "\n".join(head + out + lines[table_end:]) + "\n"


def _compare_form(text: str) -> list[list[str]]:
    """Every row minus Owner in file order (a duplicate or a reorder differs), and the preamble."""
    rows = []
    for ln in text.splitlines():
        if ln.startswith("| Gate "):
            rows.append(["header", ln.strip()])
        elif ln.startswith("| ") and not ln.startswith("|---"):
            cells = _cells(ln)
            rows.append(cells[:OWNER] + cells[OWNER + 1 :])
        elif ln.startswith(("Derived by", "Generated by")):
            rows.append(["preamble", ln])
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if gates.md differs from check_quirks.py")
    args = parser.parse_args(argv)
    path = ROOT / GATES
    existing = path.read_text(encoding="utf-8")
    if not args.check:
        try:
            text = build(ROOT, existing, use_git=True)
        except ValueError as err:
            print(f"error: {err}")
            return 1
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {GATES}")
        return 0
    have = _compare_form(existing)
    try:
        want = _compare_form(build(ROOT, existing, use_git=False))
    except ValueError as err:
        print(f"error: {err}")
        return 1
    have_keys, want_keys = [r[0] for r in have], [r[0] for r in want]
    dups = [k for k in dict.fromkeys(have_keys) if have_keys.count(k) > 1]
    if have == want and not dups:
        print("gates.md is current")
        return 0
    for key in dict.fromkeys(want_keys):
        if key not in have_keys:
            print(f"missing row: {key}")
    for key in dict.fromkeys(have_keys):
        if key not in want_keys:
            print(f"stale row: {key}")
        elif key in dups:
            print(f"duplicate row: {key}")
    if sorted(have_keys) == sorted(want_keys) and have_keys != want_keys:
        print("rows out of order")
    for h, w in zip(have, want):
        if h[0] == w[0] and h != w:
            print(f"changed row: {h[0]}")
    print("gates.md drifted from check_quirks.py: run `python scripts/gates_registry.py`")
    return 1


if __name__ == "__main__":
    sys.exit(main())
